func g0(a float64, p []float64) float64 {
	return (a - 4.0 + (p[25]-1.0)*(a-4.0+(math.Exp(-math.Abs(p[24])*(a-4.0))-1.0)/math.Abs(p[24])))
}

func sumex(ex float64) float64 {
	return (1.0 + (1.0-math.Pow(ex, 19.0))/(1.0-ex)*math.Pow(ex, 0.5))
}

func sg0(ex float64, p []float64, ap []float64) float64 {
	return (g0(ap[1], p) + (g0(ap[2], p)*ex + g0(ap[3], p)*ex*ex +
		g0(ap[4], p)*math.Pow(ex, 3.0) + (g0(ap[5], p)*math.Pow(ex, 4.0)+
		g0(ap[6], p)*math.Pow(ex, 12.0))*(1.0-math.Pow(ex, 8.0))/(1.0-ex))) / sumex(ex)
}

// globe7 calculates global variations in the upper thermosphere
func (m *NRLMSISE00) globe7(p []float64, input *Input, flags *Flags, s *state) float64 {
	var t [15]float64
	dgtr := 1.74533e-2
	dr := 1.72142e-2
	hr := 0.2618
	sr := 7.2722e-5

	tloc := input.LST
	for j := 0; j < 14; j++ {
		t[j] = 0
	}

	// calculate legendre polynomials
	c := math.Sin(input.GLat * dgtr)
	s_lat := math.Cos(input.GLat * dgtr)
	c2 := c * c
	c4 := c2 * c2
	s2 := s_lat * s_lat

	s.plg[0][1] = c
	s.plg[0][2] = 0.5 * (3.0*c2 - 1.0)
	s.plg[0][3] = 0.5 * (5.0*c*c2 - 3.0*c)
	s.plg[0][4] = (35.0*c4 - 30.0*c2 + 3.0) / 8.0
	s.plg[0][5] = (63.0*c2*c2*c - 70.0*c2*c + 15.0*c) / 8.0
	s.plg[0][6] = (11.0*c*s.plg[0][5] - 5.0*s.plg[0][4]) / 6.0

	s.plg[1][1] = s_lat
	s.plg[1][2] = 3.0 * c * s_lat
	s.plg[1][3] = 1.5 * (5.0*c2 - 1.0) * s_lat
	s.plg[1][4] = 2.5 * (7.0*c2*c - 3.0*c) * s_lat
	s.plg[1][5] = 1.875 * (21.0*c4 - 14.0*c2 + 1.0) * s_lat
	s.plg[1][6] = (11.0*c*s.plg[1][5] - 6.0*s.plg[1][4]) / 5.0

	s.plg[2][2] = 3.0 * s2
	s.plg[2][3] = 15.0 * s2 * c
	s.plg[2][4] = 7.5 * (7.0*c2 - 1.0) * s2
	s.plg[2][5] = 3.0*c*s.plg[2][4] - 2.0*s.plg[2][3]
	s.plg[2][6] = (11.0*c*s.plg[2][5] - 7.0*s.plg[2][4]) / 4.0
	s.plg[2][7] = (13.0*c*s.plg[2][6] - 8.0*s.plg[2][5]) / 5.0

	s.plg[3][3] = 15.0 * s2 * s_lat
	s.plg[3][4] = 105.0 * s2 * s_lat * c
	s.plg[3][5] = (9.0*c*s.plg[3][4] - 7.0*s.plg[3][3]) / 2.0
	s.plg[3][6] = (11.0*c*s.plg[3][5] - 8.0*s.plg[3][4]) / 3.0

	if !((flags.sw[7] == 0 && flags.sw[8] == 0) && flags.sw[14] == 0) {
		s.stloc = math.Sin(hr * tloc)
		s.ctloc = math.Cos(hr * tloc)
		s.s2tloc = math.Sin(2.0 * hr * tloc)
		s.c2tloc = math.Cos(2.0 * hr * tloc)
		s.s3tloc = math.Sin(3.0 * hr * tloc)
		s.c3tloc = math.Cos(3.0 * hr * tloc)
	}

	cd32 := math.Cos(dr * (float64(input.DOY) - p[31]))
	cd18 := math.Cos(2.0 * dr * (float64(input.DOY) - p[17]))
	cd14 := math.Cos(dr * (float64(input.DOY) - p[13]))
	cd39 := math.Cos(2.0 * dr * (float64(input.DOY) - p[38]))

	// F10.7 EFFECT
	df := input.F107 - input.F107A
	s.dfa = input.F107A - 150.0
	t[0] = p[19]*df*(1.0+p[59]*s.dfa) + p[20]*df*df + p[21]*s.dfa + p[29]*math.Pow(s.dfa, 2.0)
	f1 := 1.0 + (p[47]*s.dfa+p[19]*df+p[20]*df*df)*flags.swc[1]
	f2 := 1.0 + (p[49]*s.dfa+p[19]*df+p[20]*df*df)*flags.swc[1]

	// TIME INDEPENDENT
	t[1] = (p[1]*s.plg[0][2] + p[2]*s.plg[0][4] + p[22]*s.plg[0][6]) +
		(p[14]*s.plg[0][2])*s.dfa*flags.swc[1] + p[26]*s.plg[0][1]

	// SYMMETRICAL ANNUAL
	t[2] = p[18] * cd32

	// SYMMETRICAL SEMIANNUAL
	t[3] = (p[15] + p[16]*s.plg[0][2]) * cd18

	// ASYMMETRICAL ANNUAL
	t[4] = f1 * (p[9]*s.plg[0][1] + p[10]*s.plg[0][3]) * cd14

	// ASYMMETRICAL SEMIANNUAL
	t[5] = p[37] * s.plg[0][1] * cd39

	// DIURNAL
	if flags.sw[7] != 0 {
		t71 := (p[11] * s.plg[1][2]) * cd14 * flags.swc[5]
		t72 := (p[12] * s.plg[1][2]) * cd14 * flags.swc[5]
		t[6] = f2 * ((p[3]*s.plg[1][1]+p[4]*s.plg[1][3]+p[27]*s.plg[1][5]+t71)*
			s.ctloc + (p[6]*s.plg[1][1]+p[7]*s.plg[1][3]+p[28]*s.plg[1][5]+
			t72)*s.stloc)
	}

	// SEMIDIURNAL
	if flags.sw[8] != 0 {
		t81 := (p[23]*s.plg[2][3] + p[35]*s.plg[2][5]) * cd14 * flags.swc[5]
		t82 := (p[33]*s.plg[2][3] + p[36]*s.plg[2][5]) * cd14 * flags.swc[5]
		t[7] = f2 * ((p[5]*s.plg[2][2]+p[41]*s.plg[2][4]+t81)*s.c2tloc + (p[8]*s.plg[2][2]+p[42]*s.plg[2][4]+t82)*s.s2tloc)
	}

	// TERDIURNAL
	if flags.sw[14] != 0 {
		t[13] = f2 * ((p[39]*s.plg[3][3]+(p[93]*s.plg[3][4]+p[46]*s.plg[3][6])*cd14*flags.swc[5])*s.s3tloc +
			(p[40]*s.plg[3][3]+(p[94]*s.plg[3][4]+p[48]*s.plg[3][6])*cd14*flags.swc[5])*s.c3tloc)
	}

	// magnetic activity
	if flags.sw[9] == -1 {
		if p[51] != 0 {
			exp1 := math.Exp(-10800.0 * math.Sqrt(p[51]*p[51]) / (1.0 + p[138]*(45.0-math.Sqrt(input.GLat*input.GLat))))
			if exp1 > 0.99999 {
				exp1 = 0.99999
			}
			s.apt[0] = sg0(exp1, p, input.APA.A[:])
			if flags.sw[9] != 0 {
				t[8] = s.apt[0] * (p[50] + p[96]*s.plg[0][2] + p[54]*s.plg[0][4] +
					(p[125]*s.plg[0][1]+p[126]*s.plg[0][3]+p[127]*s.plg[0][5])*cd14*flags.swc[5] +
					(p[128]*s.plg[1][1]+p[129]*s.plg[1][3]+p[130]*s.plg[1][5])*flags.swc[7]*
						math.Cos(hr*(tloc-p[131])))
			}
		}
	} else {
		apd := input.AP - 4.0
		p44 := p[43]
		p45 := p[44]
		if p44 < 0 {
			p44 = 1.0e-5
		}
		s.apdf = apd + (p45-1.0)*(apd+(math.Exp(-p44*apd)-1.0)/p44)
		if flags.sw[9] != 0 {
			t[8] = s.apdf * (p[32] + p[45]*s.plg[0][2] + p[34]*s.plg[0][4] +
				(p[100]*s.plg[0][1]+p[101]*s.plg[0][3]+p[102]*s.plg[0][5])*cd14*flags.swc[5] +
				(p[121]*s.plg[1][1]+p[122]*s.plg[1][3]+p[123]*s.plg[1][5])*flags.swc[7]*
					math.Cos(hr*(tloc-p[124])))
		}
	}

	if flags.sw[10] != 0 && input.GLong > -1000.0 {
		// longitudinal
		if flags.sw[11] != 0 {
			t[10] = (1.0 + p[80]*s.dfa*flags.swc[1]) *
				((p[64]*s.plg[1][2]+p[65]*s.plg[1][4]+p[66]*s.plg[1][6]+
					p[103]*s.plg[1][1]+p[104]*s.plg[1][3]+p[105]*s.plg[1][5]+
					flags.swc[5]*(p[109]*s.plg[1][1]+p[110]*s.plg[1][3]+p[111]*s.plg[1][5])*cd14)*
					math.Cos(dgtr*input.GLong) +
					(p[90]*s.plg[1][2]+p[91]*s.plg[1][4]+p[92]*s.plg[1][6]+
						p[106]*s.plg[1][1]+p[107]*s.plg[1][3]+p[108]*s.plg[1][5]+
						flags.swc[5]*(p[112]*s.plg[1][1]+p[113]*s.plg[1][3]+p[114]*s.plg[1][5])*cd14)*
						math.Sin(dgtr*input.GLong))
		}
		// ut and mixed ut, longitude
		if flags.sw[12] != 0 {
			t[11] = (1.0 + p[95]*s.plg[0][1]) * (1.0 + p[81]*s.dfa*flags.swc[1]) *
				(1.0 + p[119]*s.plg[0][1]*flags.swc[5]*cd14) *
				((p[68]*s.plg[0][1] + p[69]*s.plg[0][3] + p[70]*s.plg[0][5]) *
					math.Cos(sr*(input.Sec-p[71])))
			t[11] += flags.swc[11] *
				(p[76]*s.plg[2][3] + p[77]*s.plg[2][5] + p[78]*s.plg[2][7]) *
				math.Cos(sr*(input.Sec-p[79])+2.0*dgtr*input.GLong) * (1.0 + p[137]*s.dfa*flags.swc[1])
		}
		// ut, longitude magnetic activity
		if flags.sw[13] != 0 {
			if flags.sw[9] == -1 {
				if p[51] != 0 {
					t[12] = s.apt[0]*flags.swc[11]*(1.+p[132]*s.plg[0][1])*
						((p[52]*s.plg[1][2]+p[98]*s.plg[1][4]+p[67]*s.plg[1][6])*
							math.Cos(dgtr*(input.GLong-p[97]))) +
						s.apt[0]*flags.swc[11]*flags.swc[5]*
							(p[133]*s.plg[1][1]+p[134]*s.plg[1][3]+p[135]*s.plg[1][5])*
							cd14*math.Cos(dgtr*(input.GLong-p[136])) +
						s.apt[0]*flags.swc[12]*
							(p[55]*s.plg[0][1]+p[56]*s.plg[0][3]+p[57]*s.plg[0][5])*
							math.Cos(sr*(input.Sec-p[58]))
				}
			} else {
				t[12] = s.apdf*flags.swc[11]*(1.0+p[120]*s.plg[0][1])*
					((p[60]*s.plg[1][2]+p[61]*s.plg[1][4]+p[62]*s.plg[1][6])*
						math.Cos(dgtr*(input.GLong-p[63]))) +
					s.apdf*flags.swc[11]*flags.swc[5]*
						(p[115]*s.plg[1][1]+p[116]*s.plg[1][3]+p[117]*s.plg[1][5])*
						cd14*math.Cos(dgtr*(input.GLong-p[118])) +
					s.apdf*flags.swc[12]*
						(p[55]*s.plg[0][1]+p[56]*s.plg[0][3]+p[57]*s.plg[0][5])*
						math.Cos(sr*(input.Sec-p[58]))
			}
		}
	}

	total := p[30]
	for i := 0; i < 14; i++ {
		total += t[i] * flags.sw[i+1]
	}
	return total
}

// glob7s is the variation of globe for the lower atmosphere
func (m *NRLMSISE00) glob7s(p []float64, input *Input, flags *Flags, s *state) float64 {
	var t [14]float64
	dr := 1.72142e-2

	cd32 := math.Cos(dr * (float64(input.DOY) - p[31]))
	cd18 := math.Cos(2.0 * dr * (float64(input.DOY) - p[17]))
	cd14 := math.Cos(dr * (float64(input.DOY) - p[13]))
	cd39 := math.Cos(2.0 * dr * (float64(input.DOY) - p[38]))

	// F10.7
	t[0] = p[21] * s.dfa

	// Time Independent
	t[1] = p[1]*s.plg[0][2] + p[2]*s.plg[0][4] + p[22]*s.plg[0][6] + p[26]*s.plg[0][1] + p[14]*s.plg[0][3] + p[59]*s.plg[0][5]

	// Symmetrical Annual
	t[2] = (p[18] + p[47]*s.plg[0][2] + p[29]*s.plg[0][4]) * cd32

	// Symmetrical Semiannual
	t[3] = (p[15] + p[16]*s.plg[0][2] + p[30]*s.plg[0][4]) * cd18

	// Asymmetrical Annual
	t[4] = (p[9]*s.plg[0][1] + p[10]*s.plg[0][3] + p[20]*s.plg[0][5]) * cd14

	// Asymmetrical Semiannual
	t[5] = (p[37] * s.plg[0][1]) * cd39

	// Diurnal
	if flags.sw[7] != 0 {
		t71 := p[11] * s.plg[1][2] * cd14 * flags.swc[5]
		t72 := p[12] * s.plg[1][2] * cd14 * flags.swc[5]
		t[6] = ((p[3]*s.plg[1][1]+p[4]*s.plg[1][3]+t71)*s.ctloc + (p[6]*s.plg[1][1]+p[7]*s.plg[1][3]+t72)*s.stloc)
	}

	// Semidiurnal
	if flags.sw[8] != 0 {
		t81 := (p[23]*s.plg[2][3] + p[35]*s.plg[2][5]) * cd14 * flags.swc[5]
		t82 := (p[33]*s.plg[2][3] + p[36]*s.plg[2][5]) * cd14 * flags.swc[5]
		t[7] = ((p[5]*s.plg[2][2]+p[41]*s.plg[2][4]+t81)*s.c2tloc + (p[8]*s.plg[2][2]+p[42]*s.plg[2][4]+t82)*s.s2tloc)
	}

	// Terdiurnal
	if flags.sw[14] != 0 {
		t[13] = p[39]*s.plg[3][3]*s.s3tloc + p[40]*s.plg[3][3]*s.c3tloc
	}

	// Magnetic Activity
	if flags.sw[9] != 0 {
		if flags.sw[9] == 1 {
			t[8] = s.apdf * (p[32] + p[45]*s.plg[0][2]*flags.swc[2])
		} else if flags.sw[9] == -1 {
			t[8] = (p[50]*s.apt[0] + p[96]*s.plg[0][2]*s.apt[0]*flags.swc[2])
		}
	}

	tt := 0.0
	for i := 0; i < 14; i++ {
		tt += math.Abs(flags.sw[i+1]) * t[i]
	}
	return tt
}

func (m *NRLMSISE00) spline(x, y []float64, n int, yp1, ypn float64, y2 []float64) {
	u := make([]float64, n)
	if yp1 > 0.99e30 {
		y2[0] = 0
		u[0] = 0
	} else {
		y2[0] = -0.5
		u[0] = (3.0 / (x[1] - x[0])) * ((y[1]-y[0])/(x[1]-x[0]) - yp1)
	}
	for i := 1; i < n-1; i++ {
		sig := (x[i] - x[i-1]) / (x[i+1] - x[i-1])
		p := sig*y2[i-1] + 2.0
		y2[i] = (sig - 1.0) / p
		u[i] = (6.0*((y[i+1]-y[i])/(x[i+1]-x[i])-(y[i]-y[i-1])/(x[i]-x[i-1]))/(x[i+1]-x[i-1]) - sig*u[i-1]) / p
	}
	var qn, un float64
	if ypn > 0.99e30 {
		qn = 0
		un = 0
	} else {
		qn = 0.5
		un = (3.0 / (x[n-1] - x[n-2])) * (ypn - (y[n-1]-y[n-2])/(x[n-1]-x[n-2]))
	}
	y2[n-1] = (un - qn*u[n-2]) / (qn*y2[n-2] + 1.0)
	for k := n - 2; k >= 0; k-- {
		y2[k] = y2[k]*y2[k+1] + u[k]
	}
}

func (m *NRLMSISE00) splint(xa, ya, y2a []float64, n int, x float64, y *float64) {
	klo, khi := 0, n-1
	for khi-klo > 1 {
		k := (khi + klo) / 2
		if xa[k] > x {
			khi = k
		} else {
			klo = k
		}
	}
	h := xa[khi] - xa[klo]
	if h == 0.0 {
		return
	}
	a := (xa[khi] - x) / h
	b := (x - xa[klo]) / h
	*y = a*ya[klo] + b*ya[khi] + ((a*a*a-a)*y2a[klo]+(b*b*b-b)*y2a[khi])*h*h/6.0
}

func (m *NRLMSISE00) splini(xa, ya, y2a []float64, n int, x float64, yi *float64) {
	*yi = 0
	klo, khi := 0, 1
	var xx, h, a, b, a2, b2 float64
	for x > xa[klo] && khi < n {
		xx = x
		if khi < n-1 {
			if x < xa[khi] {
				xx = x
			} else {
				xx = xa[khi]
			}
		}
		h = xa[khi] - xa[klo]
		a = (xa[khi] - xx) / h
		b = (xx - xa[klo]) / h
		a2, b2 = a*a, b*b
		*yi += ((1.0-a2)*ya[klo]/2.0 + b2*ya[khi]/2.0 + ((-(1.0+a2*a2)/4.0+a2/2.0)*y2a[klo]+(b2*b2/4.0-b2/2.0)*y2a[khi])*h*h/6.0) * h
		klo++
		khi++
	}
}

// densu implements the upper thermosphere profile (above 100km)
func (m *NRLMSISE00) densu(alt, dlb, tinf, tlb, xm, alpha float64, tz *float64, zlb, s2 float64, mn1 int, zn1, tn1, tgn1 []float64, s *state) float64 {
	var za, z, zg2, tt, ta, dta, z1, z2, t1, t2, zg, zgdif, x, y, yd1, yd2 float64
	var mn int
	var glb, gamma, expl, gamm, yi, densa, densu_temp float64
	rgas := 831.4
	xs := make([]float64, 5)
	ys := make([]float64, 5)
	y2out := make([]float64, 5)

	za = zn1[0]
	if alt > za {
		z = alt
	} else {
		z = za
	}

	zg2 = zeta(z, zlb, s.re)
	tt = tinf - (tinf-tlb)*math.Exp(-s2*zg2)
	ta = tt
	*tz = tt
	densu_temp = *tz

	if alt < za {
		dta = (tinf - ta) * s2 * math.Pow((s.re+zlb)/(s.re+za), 2.0)
		tgn1[0] = dta
		tn1[0] = ta
		if alt > zn1[mn1-1] {
			z = alt
		} else {
			z = zn1[mn1-1]
		}
		mn = mn1
		z1 = zn1[0]
		z2 = zn1[mn-1]
		t1 = tn1[0]
		t2 = tn1[mn-1]
		zg = zeta(z, z1, s.re)
		zgdif = zeta(z2, z1, s.re)
		for k := 0; k < mn; k++ {
			xs[k] = zeta(zn1[k], z1, s.re) / zgdif
			ys[k] = 1.0 / tn1[k]
		}
		yd1 = -tgn1[0] / (t1 * t1) * zgdif
		yd2 = -tgn1[1] / (t2 * t2) * zgdif * math.Pow((s.re+z2)/(s.re+z1), 2.0)
		m.spline(xs, ys, mn, yd1, yd2, y2out)
		x = zg / zgdif
		m.splint(xs, ys, y2out, mn, x, &y)
		*tz = 1.0 / y
		densu_temp = *tz
	}

	if xm == 0 {
		return densu_temp
	}

	glb = s.gsurf / math.Pow(1.0+zlb/s.re, 2.0)
	gamma = xm * glb / (s2 * rgas * tinf)
	expl = math.Exp(-s2 * gamma * zg2)
	if expl > 50.0 {
		expl = 50.0
	}
	if tt <= 0 {
		expl = 50.0
	}

	densa = dlb * math.Pow(tlb/tt, 1.0+alpha+gamma) * expl
	densu_temp = densa
	if alt >= za {
		return densu_temp
	}

	glb = s.gsurf / math.Pow(1.0+z1/s.re, 2.0)
	gamm = xm * glb * zgdif / rgas
	m.splini(xs, ys, y2out, mn, x, &yi)
	expl = gamm * yi
	if expl > 50.0 {
		expl = 50.0
	}
	if *tz <= 0 {
		expl = 50.0
	}
	densu_temp = densu_temp * math.Pow(t1/(*tz), 1.0+alpha) * math.Exp(-expl)
	return densu_temp
}

// densm calculates density for lower atmosphere altitudes
func (m *NRLMSISE00) densm(alt, d0, xm float64, tz *float64, mn3 int, zn3, tn3, tgn3 []float64, mn2 int, zn2, tn2, tgn2 []float64, s *state) float64 {
	var z, z1, z2, t1, t2, zg, zgdif, x, y, yd1, yd2 float64
	var mn int
	var glb, gamm, expl, yi, densm_tmp float64
	rgas := 831.4
	xs := make([]float64, 10)
	ys := make([]float64, 10)
	y2out := make([]float64, 10)

	densm_tmp = d0
	if alt > zn2[0] {
		if xm == 0.0 {
			return *tz
		} else {
			return d0
		}
	}

	if alt > zn2[mn2-1] {
		z = alt
	} else {
		z = zn2[mn2-1]
	}
	mn = mn2
	z1 = zn2[0]
	z2 = zn2[mn-1]
	t1 = tn2[0]
	t2 = tn2[mn-1]
	zg = zeta(z, z1, s.re)
	zgdif = zeta(z2, z1, s.re)

	for k := 0; k < mn; k++ {
		xs[k] = zeta(zn2[k], z1, s.re) / zgdif
		ys[k] = 1.0 / tn2[k]
	}
	yd1 = -tgn2[0] / (t1 * t1) * zgdif
	yd2 = -tgn2[1] / (t2 * t2) * zgdif * math.Pow((s.re+z2)/(s.re+z1), 2.0)

	m.spline(xs, ys, mn, yd1, yd2, y2out)
	x = zg / zgdif
	m.splint(xs, ys, y2out, mn, x, &y)
	*tz = 1.0 / y

	if xm != 0.0 {
		glb = s.gsurf / math.Pow(1.0+z1/s.re, 2.0)
		gamm = xm * glb * zgdif / rgas
		m.splini(xs, ys, y2out, mn, x, &yi)
		expl = gamm * yi
		if expl > 50.0 {
			expl = 50.0
		}
		densm_tmp = densm_tmp * (t1 / *tz) * math.Exp(-expl)
	}

	if alt > zn3[0] {
		if xm == 0.0 {
			return *tz
		} else {
			return densm_tmp
		}
	}

	z = alt
	mn = mn3
	z1 = zn3[0]
	z2 = zn3[mn-1]
	t1 = tn3[0]
	t2 = tn3[mn-1]
	zg = zeta(z, z1, s.re)
	zgdif = zeta(z2, z1, s.re)

	for k := 0; k < mn; k++ {
		xs[k] = zeta(zn3[k], z1, s.re) / zgdif
		ys[k] = 1.0 / tn3[k]
	}
	yd1 = -tgn3[0] / (t1 * t1) * zgdif
	yd2 = -tgn3[1] / (t2 * t2) * zgdif * math.Pow((s.re+z2)/(s.re+z1), 2.0)

	m.spline(xs, ys, mn, yd1, yd2, y2out)
	x = zg / zgdif
	m.splint(xs, ys, y2out, mn, x, &y)
	*tz = 1.0 / y

	if xm != 0.0 {
		glb = s.gsurf / math.Pow(1.0+z1/s.re, 2.0)
		gamm = xm * glb * zgdif / rgas
		m.splini(xs, ys, y2out, mn, x, &yi)
		expl = gamm * yi
		if expl > 50.0 {
			expl = 50.0
		}
		densm_tmp = densm_tmp * (t1 / *tz) * math.Exp(-expl)
	}
	if xm == 0.0 {
		return *tz
	} else {
		return densm_tmp
	}
}

// GTD7 is the primary entry point for density and temperature
func (m *NRLMSISE00) GTD7(input *Input, flags *Flags) Output {
	var out Output
	s := &state{}

	m.mu.RLock()
	defer m.mu.RUnlock()

	// Initial time-independent vars
	s.dfa = input.F107A - 150.0
	s.gsurf, s.re = m.glatf(input.GLat)

	// Switch configuration
	if flags.switches[0] == 0 {
		for i := 1; i < 24; i++ {
			flags.sw[i] = 1.0
			flags.swc[i] = 1.0
		}
	} else {
		for i := 1; i < 24; i++ {
			if flags.switches[i] == 1 {
				flags.sw[i] = 1.0
			} else {
				flags.sw[i] = 0.0
			}
			if flags.switches[i] > 0 {
				flags.swc[i] = 1.0
			} else {
				flags.swc[i] = 0.0
			}
		}
		flags.sw[9] = float64(flags.switches[9])
		flags.swc[9] = float64(flags.switches[9])
	}

	alt := input.Alt
	if alt > 1000 {
		alt = 1000
	}
	if alt < 0 {
		alt = 0
	}

	// 1. Exospheric temperature: tinf = ptm[0] * pt[0] * (1 + sw[16]*globe7(pt))
	g0 := m.globe7(pt[:], input, flags, s)
	tinf := ptm[0] * pt[0] * (1.0 + flags.sw[16]*g0)
	if tinf < 100.0 || math.IsNaN(tinf) {
		tinf = 100.0
	}

	// 2. Temperature at lower boundary 120 km
	sOutput := m.glob7s(ps[:], input, flags, s)
	denom := 1.0 - flags.sw[17]*sOutput
	if math.Abs(denom) < 1e-6 {
		denom = 1e-6 // Prevent division by zero
	}
	tlb := ptm[1] * pt[0] / denom
	if tlb < 100.0 || math.IsNaN(tlb) {
		tlb = 100.0
	}

	out.Temperatures[0] = tinf
	out.Temperatures[1] = tlb

	// 3. Standard MSIS profile altitude nodes (km) and temperature mesh
	zn1 := []float64{120.0, 110.0, 100.0, 90.0, 72.5}
	tn1 := []float64{tlb, ptm[2], ptm[3], ptm[7], ptm[4]}
	tgn1 := []float64{ptm[8], 0.0}

	zn2 := []float64{72.5, 55.0, 45.0, 32.5}
	tn2 := []float64{ptm[4], 200.0, 220.0, ptm[5]}
	tgn2 := []float64{0.01, 0.0}

	zn3 := []float64{32.5, 20.0, 15.0, 10.0, 0.0}
	tn3 := []float64{ptm[5], 220.0, 210.0, 240.0, 288.15}
	tgn3 := []float64{0.01, -0.0065}

	// 4. Species densities using pdm base values
	// Species: 0=He, 1=O, 2=N2, 3=O2, 4=Ar, 5=Total, 6=H, 7=N, 8=Anom.O
	// Precise Atomic Weights (Sovereign Baseline)
	// He=4.0026, O=15.9994, N2=28.0134, O2=31.9988, Ar=39.948, H=1.0079, N=14.0067
	mweight := []float64{4.0026, 15.9994, 28.0134, 31.9988, 39.948, 1.0079, 1.0079, 14.0067, 15.9994}
	// pdm species index mapping: He=0, O=1, N2=2, O2=3, Ar=4, H=5, N=6, AnomalousO=7
	pdmIdx := []int{0, 1, 2, 3, 4, -1, 5, 6, 7}

	for i := 0; i < 9; i++ {
		if i == 5 {
			continue
		} // Total is computed below
		pi := pdmIdx[i]
		if pi < 0 || pi >= len(pdm) {
			continue
		}

		gvar := m.globe7(pd[i][:], input, flags, s)
		var dens float64
		var tz float64
		zlb := pdm[pi][2] // Reference lower boundary altitude for this species
		if zlb < 72.5 {
			zlb = 100.0
		}
		if alt >= zlb {
			// Upper thermosphere: Bates diffusive equilibrium profile
			dlb := pdm[pi][0] * math.Exp(flags.sw[20]*gvar) * pd[i][0]
			dens = m.densu(alt, dlb, tinf, tlb, mweight[i], 0.0, &tz, zlb, 0.02, 5, zn1, tn1, tgn1, s)
		} else {
			// Lower atmosphere: mixing-dominated profile
			dens = m.densm(alt, pdm[pi][0]*pd[i][0], mweight[i], &tz, 5, zn3, tn3, tgn3, 4, zn2, tn2, tgn2, s)
			v := m.glob7s(pd[i][:], input, flags, s)
			if v > 0.999 {
				v = 0.999
			}
			dens = dens / (1.0 - v)
		}
		out.Densities[i] = dens
		if i == 2 && alt < 100 {
			out.Temperatures[1] = tz
		}
	}

	if alt >= 100 {
		out.Temperatures[1] = tinf
	}

	// 4. Total mass density (Unit: kg/m^3)
	// 1.660538921e-27 kg per AMU
	// MSIS returns particles/cm^3 -> particles/m^3 is *1e6
	total := 0.0
	for i := 0; i < 9; i++ {
		if i == 5 {
			continue
		}
		total += out.Densities[i] * mweight[i] * 1.660538921e-27 * 1e6
	}
	out.Densities[5] = total

	return out
}

// GTD7D returns the effective total mass density (kg/m^3)
func (m *NRLMSISE00) GTD7D(input *Input, flags *Flags) float64 {
	out := m.GTD7(input, flags)
	return out.Densities[5]
}

// JDToMSIS converts Julian Date to MSIS Time components
func JDToMSIS(jd float64) (doy int, sec float64) {
	unix := (jd - 2440587.5) * 86400.0
	t := time.Unix(int64(unix), 0).UTC()
	doy = t.YearDay()
	sec = float64(t.Hour()*3600 + t.Minute()*60 + t.Second())
	return
}

// ECIToGeodetic performs a first-order TEME ECI to Geodetic conversion
func ECIToGeodetic(x, y, z, jd float64) (lat, long, alt float64) {
	r := math.Sqrt(x*x + y*y + z*z)
	alt = r - 6378.137 // km

	lat = math.Asin(z/r) * 180.0 / math.Pi

	t_utc := (jd - 2451545.0) / 36525.0
	gmst := 6.30038809898*(jd-2451545.0) + 4.8949612127 + (0.0000213366+0.00000006003*t_utc)*t_utc
	gmst = math.Mod(gmst, 2.0*math.Pi)
	if gmst < 0 {
		gmst += 2.0 * math.Pi
	}

	lon_rad := math.Atan2(y, x) - gmst
	long = math.Mod(lon_rad*180.0/math.Pi, 360.0)
	if long < -180 {
		long += 360
	} else if long > 180 {
		long -= 360
	}
	return
}
