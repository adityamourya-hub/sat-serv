func (m *NRLMSISE00) glatf(lat float64) (gv, reff float64) {
	dgtr := 1.74533e-2
	c2 := math.Cos(2.0 * dgtr * lat)
	gv = 980.616 * (1.0 - 0.0026373*c2)
	reff = 2.0 * gv / (3.085462e-6 + 2.27e-9*c2) * 1.0e-5
	return
}

func ccor(alt, r, h1, zh float64) float64 {
	e := (alt - zh) / h1
	if e > 70 {
		return math.Exp(0)
	}
	if e < -70 {
		return math.Exp(r)
	}
	ex := math.Exp(e)
	e = r / (1.0 + ex)
	return math.Exp(e)
}

func ccor2(alt, r, h1, zh, h2 float64) float64 {
	e1 := (alt - zh) / h1
	e2 := (alt - zh) / h2
	if e1 > 70 || e2 > 70 {
		return math.Exp(0)
	}
	if e1 < -70 && e2 < -70 {
		return math.Exp(r)
	}
	ex1 := math.Exp(e1)
	ex2 := math.Exp(e2)
	ccor2v := r / (1.0 + 0.5*(ex1+ex2))
	return math.Exp(ccor2v)
}

