// NRLMSISE00 implements the Neutral Atmosphere Empirical Model (2001).
// This is a pure Go port of the NASA/NRL reference C implementation.
type NRLMSISE00 struct {
	mu sync.RWMutex
}

func NewNRLMSISE00() *NRLMSISE00 {
	return &NRLMSISE00{}
}

