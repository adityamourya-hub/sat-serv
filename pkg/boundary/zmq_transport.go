//
// Zero-Copy ZMQ Transport with FlatBuffers for Sovereign SDA Operations
// Ensures <50ms mechanical settle-time by bypassing Go GC entirely
//
// Key Features:
// - sync.Pool for FlatBuffer builders (zero heap allocations in 100Hz loop)
// - Zero-copy reads: cast byte array directly into FlatBuffer struct
// - Cryptographic gating with GateSig (Hessian Hash authentication)
// - Non-blocking ZMQ for real-time actuation

package boundary

import (
	"fmt"
	"ssis/pkg/boundary/AxiomZero/Boundary"
	"sync"
	"time"

	flatbuffers "github.com/google/flatbuffers/go"
	zmq "github.com/pebbe/zmq4"
	// Generated by flatc
)

// Zero-Allocation Builder Pool
// Critical for 100Hz reflex loop - ensures zero heap allocations
var builderPool = sync.Pool{
	New: func() interface{} {
		return flatbuffers.NewBuilder(256) // Pre-allocate 256 bytes
	},
}

// =============================================================================
// TIER 3 ACTUATION (Command Publisher)
// =============================================================================

// PublishSlewCommand publishes a slew command via ZMQ with FlatBuffers
// Uses sync.Pool to ensure zero heap allocations
//
// Parameters:
//   - socket: ZMQ PUSH socket
//   - targetID: RSO NORAD ID or internal catalog ID
//   - az: Target azimuth [rad]
//   - el: Target elevation [rad]
//   - rate: Angular velocity [rad/s]
//   - accel: Angular acceleration [rad/s^2]
//   - sig: 8-byte GateSig (truncated Hessian Hash for authentication)
//
// Returns error if ZMQ send fails
func PublishSlewCommand(socket *zmq.Socket, targetID uint32, az, el, rate, accel float64, sig []byte) error {
	// Get builder from pool (zero allocation)
	builder := builderPool.Get().(*flatbuffers.Builder)
	builder.Reset()
	defer builderPool.Put(builder)

	// 1. Create the Signature Vector (End-to-End Auth)
	// Build vector in reverse order (FlatBuffers requirement)
	Boundary.SlewCommandStartGateSigVector(builder, len(sig))
	for i := len(sig) - 1; i >= 0; i-- {
		builder.PrependByte(sig[i])
	}
	sigOffset := builder.EndVector(len(sig))

	// 2. Build the Command (Zero-Copy packing)
	Boundary.SlewCommandStart(builder)
	Boundary.SlewCommandAddTargetId(builder, targetID)
	Boundary.SlewCommandAddTimestampNs(builder, time.Now().UnixNano())
	Boundary.SlewCommandAddAzimuthCmd(builder, az)
	Boundary.SlewCommandAddElevationCmd(builder, el)
	Boundary.SlewCommandAddTiltRate(builder, rate)
	Boundary.SlewCommandAddTiltAccel(builder, accel)
	Boundary.SlewCommandAddPriority(builder, 9) // Critical Override
	Boundary.SlewCommandAddGateSig(builder, sigOffset)
	cmdOffset := Boundary.SlewCommandEnd(builder)

	builder.Finish(cmdOffset)

	// 3. Fire over ZMQ PUSH socket (Non-blocking)
	_, err := socket.SendBytes(builder.FinishedBytes(), zmq.DONTWAIT)
	return err
}

// =============================================================================
// TIER 1 INGEST (Telemetry Subscriber)
// =============================================================================

// TelemetryHandler processes incoming telemetry packets
type TelemetryHandler func(*Boundary.TelemetryPacket)

// IngestTelemetryStream subscribes to ZMQ telemetry stream
// Zero-copy read: casts byte array directly into FlatBuffer struct
//
// Parameters:
//   - endpoint: ZMQ endpoint (e.g., "tcp://host:port")
//   - handler: Callback function for each telemetry packet
//
// This function blocks - run in goroutine in production
func IngestTelemetryStream(endpoint string, handler TelemetryHandler) error {
	subscriber, err := zmq.NewSocket(zmq.SUB)
	if err != nil {
		return fmt.Errorf("failed to create SUB socket: %w", err)
	}
	defer subscriber.Close()

	err = subscriber.Connect(endpoint)
	if err != nil {
		return fmt.Errorf("failed to connect to %s: %w", endpoint, err)
	}

	err = subscriber.SetSubscribe("") // Subscribe to all topics
	if err != nil {
		return fmt.Errorf("failed to subscribe: %w", err)
	}

	for {
		// Read raw bytes from ZMQ
		msg, err := subscriber.RecvBytes(0)
		if err != nil {
			// Log error in production, continue loop
			continue
		}

		// Zero-Copy Read: Cast the byte array directly into the FlatBuffer struct
		// No deserialization step - reads directly from memory
		packet := Boundary.GetRootAsTelemetryPacket(msg, 0)

		// Invoke handler (typically pushes to Reflex Kernel channel)
		handler(packet)
	}
}

// =============================================================================
// HELPER: Create ZMQ Socket
// =============================================================================

// NewSlewCommandSocket creates a ZMQ PUSH socket for actuation
func NewSlewCommandSocket(endpoint string) (*zmq.Socket, error) {
	socket, err := zmq.NewSocket(zmq.PUSH)
	if err != nil {
		return nil, fmt.Errorf("failed to create PUSH socket: %w", err)
	}

	err = socket.Connect(endpoint)
	if err != nil {
		socket.Close()
		return nil, fmt.Errorf("failed to connect to %s: %w", endpoint, err)
	}

	return socket, nil
}
